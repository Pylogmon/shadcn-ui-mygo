// Command generate verifies the pinned original assets and regenerates the
// independent family entry points. It needs no non-standard Go dependency.
package main

import (
	"bytes"
	"crypto/sha1"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"
)

type source struct {
	Path, GitBlob, SHA256, Asset string
	Repository, Commit           string
	Bytes                        int
	License                      bool
}
type derived struct {
	Asset, SHA256 string
	Bytes         int
}
type family struct {
	ID, Title, Kind, Family string
	Weights                 []int
	Italic                  bool
	Sources, Documents      []source
	Derived                 []derived
}
type manifest struct {
	Repository, Commit string
	Families           []family
	ShadcnDefinitions  source
	ShadcnPicker       source
}

func main() {
	cache := flag.String("source-dir", "", "optional directory containing the original upstream paths")
	download := flag.Bool("download", false, "download missing assets from the pinned official commit")
	flag.Parse()
	raw, err := os.ReadFile("manifest.json")
	must(err)
	var m manifest
	must(json.Unmarshal(raw, &m))
	if m.Repository != "https://github.com/google/fonts" || len(m.Families) != 26 || len(m.Commit) != 40 {
		panic("fonts: unexpected source manifest")
	}
	client := &http.Client{Timeout: 45 * time.Second}
	for _, s := range []source{m.ShadcnDefinitions, m.ShadcnPicker} {
		data, err := os.ReadFile(s.Asset)
		must(err)
		verifyOriginal(s, data)
	}
	for _, f := range m.Families {
		for _, s := range append(append([]source(nil), f.Sources...), f.Documents...) {
			data, err := os.ReadFile(s.Asset)
			if err != nil && *cache != "" {
				data, err = os.ReadFile(filepath.Join(*cache, filepath.FromSlash(s.Path)))
			}
			if err != nil && *download {
				repository, commit := m.Repository, m.Commit
				if s.Repository != "" {
					repository, commit = s.Repository, s.Commit
				}
				if !strings.HasPrefix(repository, "https://github.com/") || len(commit) != 40 {
					panic("fonts: unexpected upstream repository")
				}
				u := "https://raw.githubusercontent.com/" + strings.TrimPrefix(repository, "https://github.com/") + "/" + commit + "/" + escapePath(s.Path)
				res, requestErr := client.Get(u)
				must(requestErr)
				if res.StatusCode != http.StatusOK {
					res.Body.Close()
					panic(fmt.Sprintf("fonts: download %s: %s", s.Path, res.Status))
				}
				data, err = io.ReadAll(res.Body)
				must(res.Body.Close())
			}
			must(err)
			verifyOriginal(s, data)
			must(os.MkdirAll(filepath.Dir(s.Asset), 0755))
			must(os.WriteFile(s.Asset, data, 0644))
		}
		for _, d := range f.Derived {
			data, err := os.ReadFile(d.Asset)
			if err != nil {
				panic("fonts: restore derived instance with internal/generate/static-instance.py: " + d.Asset)
			}
			hash := sha256.Sum256(data)
			if len(data) != d.Bytes || hex.EncodeToString(hash[:]) != d.SHA256 {
				panic("fonts: changed derived instance " + d.Asset)
			}
		}
		generateFamily(f)
	}
	generateCatalogue(m.Families)
	fmt.Printf("verified and generated %d font families\n", len(m.Families))
}

func verifyOriginal(s source, data []byte) {
	sha := sha256.Sum256(data)
	blob := sha1.Sum(append([]byte(fmt.Sprintf("blob %d\x00", len(data))), data...))
	if len(data) != s.Bytes || hex.EncodeToString(sha[:]) != s.SHA256 || hex.EncodeToString(blob[:]) != s.GitBlob {
		panic("fonts: changed original asset " + s.Path)
	}
}

func escapePath(path string) string {
	parts := strings.Split(path, "/")
	for i := range parts {
		parts[i] = url.PathEscape(parts[i])
	}
	return strings.Join(parts, "/")
}

func identifier(id string) string {
	var out string
	for _, part := range strings.Split(id, "-") {
		if part == "ibm" {
			out += "IBM"
		} else if part == "dm" {
			out += "DM"
		} else if part == "eb" {
			out += "EB"
		} else if part == "jetbrains" {
			out += "JetBrains"
		} else {
			out += strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return out
}

func info(f family) string {
	weights := make([]string, len(f.Weights))
	for i, w := range f.Weights {
		weights[i] = fmt.Sprint(w)
	}
	return fmt.Sprintf("Info{ID:%q, Name:%q, Family:%q, Kind:Kind(%q), Weights:[]int{%s}, Italic:%t}", f.ID, f.Title, f.Family, f.Kind, strings.Join(weights, ","), f.Italic)
}

func generateFamily(f family) {
	var b bytes.Buffer
	name := identifier(f.ID)
	private := strings.ReplaceAll(f.ID, "-", "_")
	fmt.Fprintln(&b, "// Code generated by go generate; DO NOT EDIT.\npackage fonts\nimport _ \"embed\"")
	var assets []string
	for i, s := range f.Sources {
		v := fmt.Sprintf("%sAsset%d", private, i)
		fmt.Fprintf(&b, "//go:embed %s\nvar %s []byte\n", s.Asset, v)
		assets = append(assets, v)
	}
	for i, d := range f.Derived {
		v := fmt.Sprintf("%sDerived%d", private, i)
		fmt.Fprintf(&b, "//go:embed %s\nvar %s []byte\n", d.Asset, v)
		assets = append(assets, v)
	}
	var notices []string
	for i, s := range f.Documents {
		if !s.License {
			continue
		}
		v := fmt.Sprintf("%sLicense%d", private, i)
		fmt.Fprintf(&b, "//go:embed %s\nvar %s string\n", s.Asset, v)
		notices = append(notices, fmt.Sprintf("{Path:%q, Text:%s}", s.Asset, v))
	}
	fmt.Fprintf(&b, "var %sRegistration registration\n", private)
	fmt.Fprintf(&b, "// %s selects %s. Call Register before using Family().\nfunc %s() Font { return Font{info:%s, register:func() error { return %sRegistration.add(%q,%s) }, licenses:func() []License { return []License{%s} }} }\n", name, f.Title, name, info(f), private, f.Family, strings.Join(assets, ","), strings.Join(notices, ","))
	writeGo(strings.ReplaceAll(f.ID, "-", "_")+"_generated.go", b.Bytes())
}

func generateCatalogue(families []family) {
	var metadata bytes.Buffer
	fmt.Fprintln(&metadata, "// Code generated by go generate; DO NOT EDIT.\npackage fonts\n// Catalog lists metadata without linking any font asset.\nfunc Catalog() []Info { return []Info{")
	for _, f := range families {
		fmt.Fprintln(&metadata, info(f)+",")
	}
	fmt.Fprintln(&metadata, "} }")
	writeGo("catalog_generated.go", metadata.Bytes())
	var all bytes.Buffer
	fmt.Fprintln(&all, `// Code generated by go generate; DO NOT EDIT.
// Package all is the explicit full Create font catalogue. Importing it does not
// register fonts automatically; call Register or register a Lookup result.
package all
import (
 "fmt"
 "github.com/pylogmon/shadcn-ui-mygo/pkg/fonts"
)
// Families returns all 26 descriptors in source picker order.
func Families() []fonts.Font { return []fonts.Font{`)
	for _, f := range families {
		fmt.Fprintf(&all, "fonts.%s(),\n", identifier(f.ID))
	}
	fmt.Fprintln(&all, `} }
// Lookup finds a source font ID. This full catalogue links every font; use an
// individual fonts.Inter-style function when only selected assets are needed.
func Lookup(id string) (fonts.Font, bool) {
 for _, f := range Families() { if f.Info().ID == id { return f, true } }
 return fonts.Font{}, false
}
// Register explicitly registers every family and returns the first error.
func Register() error {
 for _, f := range Families() { if err := f.Register(); err != nil { return fmt.Errorf("fonts/all: %w", err) } }
 return nil
}`)
	writeGo("all/all_generated.go", all.Bytes())
}

func writeGo(path string, data []byte) {
	formatted, err := format.Source(data)
	must(err)
	must(os.MkdirAll(filepath.Dir(path), 0755))
	must(os.WriteFile(path, formatted, 0644))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
