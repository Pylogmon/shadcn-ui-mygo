// Command generate reproduces semantic themes and palette scales offline from
// the checked-in, checksum-pinned upstream snapshots. No Node runtime is needed.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"sort"
	"strconv"
	"strings"
)

type source struct{ File, URL, SHA256 string }
type manifest struct{ Sources []source }

func must(err error) {
	if err != nil {
		panic(err)
	}
}
func readSources() map[string]string {
	b, err := os.ReadFile("sources/manifest.json")
	must(err)
	var m manifest
	must(json.Unmarshal(b, &m))
	out := map[string]string{}
	for _, s := range m.Sources {
		b, err := os.ReadFile("sources/" + s.File)
		must(err)
		h := sha256.Sum256(b)
		if hex.EncodeToString(h[:]) != s.SHA256 {
			panic("source checksum mismatch: " + s.File)
		}
		out[s.File] = string(b)
	}
	return out
}
func names(m map[string]map[string]string) []string {
	a := make([]string, 0, len(m))
	for k := range m {
		a = append(a, k)
	}
	sort.Strings(a)
	return a
}

var (
	paletteRE = regexp.MustCompile(`(?m)^\s*--color-([a-z]+)-(\d+):\s*(oklch\([^;]+\));`)
	nameRE    = regexp.MustCompile(`(?m)^    name: "([^"]+)",`)
	lightRE   = regexp.MustCompile(`(?s)light: \{(.*?)\n      \},`)
	darkRE    = regexp.MustCompile(`(?s)dark: \{(.*?)\n      \},`)
	fieldRE   = regexp.MustCompile(`(?m)^\s*(?:"([^"]+)"|([a-zA-Z][a-zA-Z0-9-]*)):\s*"([^"]+)",?\s*$`)
)

func parseFields(block string) map[string]string {
	out := map[string]string{}
	for _, m := range fieldRE.FindAllStringSubmatch(block, -1) {
		k := m[1]
		if k == "" {
			k = m[2]
		}
		out[k] = m[3]
	}
	return out
}

// color emits the original OKLCH coordinates, preserving alpha and percent
// syntax as equivalent numeric Go arguments. Runtime conversion lives in one
// tested OKLCH implementation rather than a second generator implementation.
func color(value string) string {
	if !strings.HasPrefix(value, "oklch(") || !strings.HasSuffix(value, ")") {
		panic("unsupported source color " + value)
	}
	parts := strings.Fields(strings.ReplaceAll(value[6:len(value)-1], "/", " / "))
	var args []string
	for i, p := range parts {
		if p == "/" {
			continue
		}
		if p == "none" {
			p = "0"
		}
		n, err := strconv.ParseFloat(strings.TrimSuffix(p, "%"), 64)
		must(err)
		if strings.HasSuffix(p, "%") {
			if i == 1 {
				n *= .004
			} else {
				n /= 100
			}
		}
		args = append(args, strconv.FormatFloat(n, 'f', -1, 64))
	}
	if len(args) != 3 && len(args) != 4 {
		panic("invalid source color " + value)
	}
	return "OKLCH(" + strings.Join(args, ", ") + ")"
}

var fields = []string{
	"background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
	"primary", "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground",
	"accent", "accent-foreground", "destructive", "border", "input", "ring",
	"chart-1", "chart-2", "chart-3", "chart-4", "chart-5",
	"sidebar", "sidebar-foreground", "sidebar-primary", "sidebar-primary-foreground", "sidebar-accent", "sidebar-accent-foreground", "sidebar-border", "sidebar-ring",
}

func goField(name string) string {
	var b strings.Builder
	for _, p := range strings.Split(name, "-") {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}
func main() {
	src := readSources()
	palettes := map[string]map[string]string{}
	for _, m := range paletteRE.FindAllStringSubmatch(src["tailwind-theme.css"], -1) {
		if palettes[m[1]] == nil {
			palettes[m[1]] = map[string]string{}
		}
		palettes[m[1]][m[2]] = m[3]
	}
	if len(palettes) != 26 {
		panic(fmt.Sprintf("expected 26 Tailwind palettes, got %d", len(palettes)))
	}
	type pair struct{ light, dark map[string]string }
	themes := map[string]pair{}
	registry := src["registry-themes.ts"]
	positions := nameRE.FindAllStringSubmatchIndex(registry, -1)
	for i, pos := range positions {
		end := len(registry)
		if i+1 < len(positions) {
			end = positions[i+1][0]
		}
		name := registry[pos[2]:pos[3]]
		block := registry[pos[0]:end]
		light, dark := lightRE.FindStringSubmatch(block), darkRE.FindStringSubmatch(block)
		if len(light) != 2 || len(dark) != 2 {
			panic("missing light/dark source theme " + name)
		}
		themes[name] = pair{parseFields(light[1]), parseFields(dark[1])}
	}
	if len(themes) != 24 {
		panic(fmt.Sprintf("expected 24 registry themes, got %d", len(themes)))
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&out, "// Sources and SHA-256 checksums: sources/manifest.json.")
	fmt.Fprintln(&out, "package theme\n\nimport \"github.com/egoist/mygo/ui\"")
	fmt.Fprintln(&out, "var paletteScales = map[string][11]ui.Color{")
	shades := []int{50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950}
	for _, name := range names(palettes) {
		fmt.Fprintf(&out, "%q: {\n", name)
		for _, shade := range shades {
			v, ok := palettes[name][strconv.Itoa(shade)]
			if !ok {
				panic(fmt.Sprintf("missing %s-%d", name, shade))
			}
			fmt.Fprintf(&out, "%s, // %d\n", color(v), shade)
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "type presetPair struct { light, dark Tokens }")
	fmt.Fprintln(&out, "var registryPresets = map[string]presetPair{")
	themeNames := make([]string, 0, len(themes))
	for name := range themes {
		themeNames = append(themeNames, name)
	}
	slices.Sort(themeNames)
	for _, name := range themeNames {
		p := themes[name]
		fmt.Fprintf(&out, "%q: {\n", name)
		for i, m := range []map[string]string{p.light, p.dark} {
			base := themes["neutral"].light
			if i == 1 {
				base = themes["neutral"].dark
			}
			merged := map[string]string{}
			for k, v := range base {
				merged[k] = v
			}
			for k, v := range m {
				merged[k] = v
			}
			appearance := "light"
			if i == 1 {
				appearance = "dark"
			}
			fmt.Fprintf(&out, "%s: Tokens{Dark: %t,\n", appearance, i == 1)
			for _, field := range fields {
				value, ok := merged[field]
				if !ok {
					panic("missing semantic token " + name + "/" + field)
				}
				fmt.Fprintf(&out, "%s: %s,\n", goField(field), color(value))
			}
			// Native controls support a destructive foreground token absent
			// from the current CSS registry, so retain a documented extension.
			fg := "OKLCH(0.985, 0, 0)"
			if i == 1 {
				fg = "OKLCH(0.205, 0, 0)"
			}
			fmt.Fprintf(&out, "DestructiveForeground: %s,\n", fg)
			radius := merged["radius"]
			if radius == "" {
				radius = themes["neutral"].light["radius"]
			}
			if !strings.HasSuffix(radius, "rem") {
				panic("unsupported radius " + radius)
			}
			r, err := strconv.ParseFloat(strings.TrimSuffix(radius, "rem"), 64)
			must(err)
			fmt.Fprintf(&out, "Radius: %g, FontSize: 14, Spacing: 4,\n},\n", r*16)
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	b, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile("colors_gen.go", b, 0644))
}
